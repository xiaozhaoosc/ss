def strip_blue_spans(text: str) -> str:
    text = re.sub(r'<span\s+style="color:\s*blue;">', "", text)
    text = text.replace("</span>", "")
    return text


def normalize_text(text: str) -> str:
    return (
        text.replace("\u00a0", " ")
        .replace("“", "“")
        .replace("”", "”")
        .replace('"', '"')
        .replace("\ufeff", "")
    )


